/** عناوين قطاعات العرض (بترتيب العرض). */
export const SECTOR_TITLES = SECTOR_GROUPS.map((g) => g.title)

/** يحوّل عنوان قطاع العرض إلى قيم `sector` المطابقة في بيانات الأسهم. */
export function mapDFMSectorToDb(title: string): string[] {
  return SECTOR_GROUPS.find((g) => g.title === title)?.sectors ?? [title]
}
